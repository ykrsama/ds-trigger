#!/usr/bin/env python3
"""Export actual QKeras Q1.5 weights (HWIO NPZ) to HLS OIHW C++ arrays.

Requires NumPy only. The input must be qat_best_quantized_weights.npz, not
floating shadow weights. Default output type is ap_fixed<6,1,AP_RND_CONV,AP_SAT>.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import numpy as np

LAYERS = [
    ('input_conv1', 'conv1_kernel1', 'conv1_bias1', (4,4,3,3)),
    ('input_conv2', 'conv1_kernel2', 'conv1_bias2', (8,4,3,3)),
    ('encoder_conv1', 'conv2_kernel1', 'conv2_bias1', (8,8,3,3)),
    ('encoder_conv2', 'conv2_kernel2', 'conv2_bias2', (16,8,3,3)),
    ('decoder_conv1', 'conv3_kernel1', 'conv3_bias1', (8,24,3,3)),
    ('decoder_conv2', 'conv3_kernel2', 'conv3_bias2', (8,8,3,3)),
    ('final_conv', 'final_kernel', 'final_bias', (20,8,1,1)),
]


def extract_arrays(path):
    arrays=[]
    with np.load(path,allow_pickle=False) as data:
        used=set()
        for layer,weight,bias,shape in LAYERS:
            for name,key,expected in ((weight,layer+'.kernel',shape),(bias,layer+'.bias',(shape[0],))):
                array=data[key]
                if key.endswith('.kernel'):
                    array=array.transpose(3,2,0,1)  # HWIO -> OIHW, no kernel flip
                if array.shape!=expected or array.dtype!=np.float32:
                    raise ValueError(f'{key}: expected float32 {expected}, got {array.dtype} {array.shape}')
                if not np.isfinite(array).all() or np.any(array < -1) or np.any(array > 31/32):
                    raise ValueError(f'{key}: outside signed Q1.5 range')
                codes=np.rint(array*32).astype(np.int8)
                if not np.array_equal(array,codes.astype(np.float32)/32):
                    raise ValueError(f'{key}: values are not quantized on 1/32 grid')
                if name=='final_kernel':array=array.reshape(20,8,1,1,1)
                arrays.append((name,key,np.ascontiguousarray(array)))
                used.add(key)
        if set(data.files)!=used:raise ValueError(f'Unexported tensors: {set(data.files)-used}')
    if sum(a.size for _,_,a in arrays)!=4696:raise ValueError('Unexpected parameter count')
    return arrays


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--weights',type=Path,required=True)
    parser.add_argument('--preprocessing',type=Path,required=True)
    parser.add_argument('--metrics',type=Path,required=True)
    parser.add_argument('--output-dir',type=Path,required=True)
    args=parser.parse_args()
    arrays=extract_arrays(args.weights)
    preprocessing=json.loads(args.preprocessing.read_text())
    if preprocessing['scale']!=8 or preprocessing['transform']!='log1p(energy)/scale':
        raise ValueError('Unexpected preprocessing')
    records=[json.loads(s) for s in args.metrics.read_text().splitlines() if s.strip()]
    best=max((s for s in records if s['phase']=='qat'),key=lambda s:s['validation']['mean_iou'])
    out=args.output_dir;out.mkdir(parents=True,exist_ok=True)
    header='''// Generated by export_qkeras_hls_weights.py. Actual quantized QAT weights.
#ifndef ECAL_UNET_Q6_WEIGHTS_H
#define ECAL_UNET_Q6_WEIGHTS_H
#ifdef UNET_Q6_FLOAT_REFERENCE
namespace unet_q6_weights { using weight_t = float; using accum_t = float; }
#else
#include <ap_fixed.h>
namespace unet_q6_weights {
using weight_t = ap_fixed<6,1,AP_RND_CONV,AP_SAT>;
using accum_t = ap_fixed<24,12>;
}
#endif
namespace unet_q6_weights {
constexpr int k_input_depth=4, k_height=5, k_width=5;
constexpr int k_features_0=8, k_features_1=16;
constexpr int k_classes=5, k_final_channels=20, k_parameter_count=4696;
constexpr float k_energy_log_divisor=8.0f;
'''
    source=['#include "unet_weights.h"\nnamespace unet_q6_weights {\n']
    details=[]
    for name,key,array in arrays:
        dims=''.join(f'[{d}]' for d in array.shape)
        header+=f'// {key}; OIHW order for kernels\nextern weight_t {name}{dims};\n'
        source.append(f'weight_t {name}{dims} = {{\n')
        values=array.ravel()
        for i in range(0,array.size,8):
            source.append('    '+', '.join(f'{float(v):.5f}f' for v in values[i:i+8])+',\n')
        source.append('};\n\n')
        details.append({'name':name,'source_key':key,'shape':list(array.shape),
                        'count':int(array.size),'min':float(array.min()),'max':float(array.max())})
    header+='} // namespace unet_q6_weights\n#endif\n'
    source.append('} // namespace unet_q6_weights\n')
    (out/'unet_weights.h').write_text(header)
    (out/'unet_weights_data.cpp').write_text(''.join(source))
    shutil.copyfile(args.preprocessing,out/'preprocessing.json')
    manifest={'source_weights':str(args.weights.resolve()),
              'weights_sha256':hashlib.sha256(args.weights.read_bytes()).hexdigest(),
              'best_step':best['step'],'best_mean_iou':best['validation']['mean_iou'],
              'parameter_count':4696,'parameter_bits':28176,
              'precision':'ap_fixed<6,1,AP_RND_CONV,AP_SAT>',
              'accumulator':'ap_fixed<24,12>',
              'signed_integer_code':'round(value*32), signed range [-32,31]; raw 6-bit code = signed_code & 63',
              'source_layout':'HWIO','cpp_layout':'OIHW','arrays':details}
    (out/'weights_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    (out/'README.md').write_text('''# [8,16] 六位量化 U-Net 权重

由已完成 QAT 的最佳模型导出，详见 weights_manifest.json；不是浮点影子参数。
将 unet_weights_data.cpp 加入 HLS 工程，包含 unet_weights.h。
数组在 namespace unet_q6_weights 中，包含 7 层卷积的 kernel/bias，共 4696 参数。
默认 weight_t=ap_fixed<6,1,AP_RND_CONV,AP_SAT>，值域 [-1,0.96875]，步长 1/32。
累加器 accum_t=ap_fixed<24,12>。裸 ap_fixed<6,1> 的默认舍入/溢出语义不同。
如需无 HLS 头文件的主机测试，所有翻译单元定义 UNET_Q6_FLOAT_REFERENCE。

卷积 kernel 由 Keras HWIO 转为 OIHW，未翻转空间核；final_kernel 使用
[20][8][1][1][1]，额外单例维度用于匹配现有 FinalConv2D 接口。
原始位编码：signed_code=round(value*32)，6 位二补码为 signed_code & 63。
数值字面量在 Q1.5 网格上精确表示，无二次有损量化。

输入原始 pooled energy 的 WHD=(5,5,4)，先 log1p(energy)/8，再六位量化。
PyTorch 风格输入以深度作为通道；若输入按 WHD 存放，应转置为 DHW=(4,5,5)。
模型是 2D Conv，特征通道 [8,16]，无 GroupNorm；其余处理必须包括：
- 普通卷积也必须加对应 bias，然后 ReLU 和六位饱和量化；
- MaxPool 5x5->2x2；nearest 2x2->5x5 的索引是 [0,0,0,1,1]；
- skip 拼接先 8 通道、后 16 通道；每层输出均六位量化；
- final 卷积输出 20 通道，经六位饱和后按 class*4+depth 恢复；
- 分类直接对 5 类 logits 取 argmax；概率可在软件执行 Softmax。
权重文件不包含 log1p 的硬件实现，也不自动修改旧 unet 推理代码。
''')
    print(f'Exported {len(arrays)} arrays, 4696 parameters; best step {best["step"]}, MeanIoU {best["validation"]["mean_iou"]}')


if __name__=='__main__':main()
