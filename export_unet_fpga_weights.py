#!/usr/bin/env python3
"""Export UNet3DFPGA (layer_order=cr) checkpoint to HLS C++ weight arrays.

python export_unet_fpga_weights.py --checkpoint BEST.pytorch --config CONFIG.yaml \
    --output-dir unet/weights_16_pooled_554
No PyTorch model import is needed. Default C++ type is float; HLS builds can
use -DUNET_FPGA_FIXED_POINT for ap_fixed<32,16>, or define UNET_FPGA_WEIGHT_TYPE.
"""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import torch
import yaml

LAYERS = [
    ('conv1_kernel1', 'conv1_bias1', 'input_conv.SingleConv1.conv'),
    ('conv1_kernel2', 'conv1_bias2', 'input_conv.SingleConv2.conv'),
    ('conv2_kernel1', 'conv2_bias1', 'encoder.1.SingleConv1.conv'),
    ('conv2_kernel2', 'conv2_bias2', 'encoder.1.SingleConv2.conv'),
    ('conv3_kernel1', 'conv3_bias1', 'decoder_conv.SingleConv1.conv'),
    ('conv3_kernel2', 'conv3_bias2', 'decoder_conv.SingleConv2.conv'),
    ('final_kernel', 'final_bias', 'final_conv'),
]


def extract_arrays(checkpoint, config):
    m = config['model']
    if m['name'] != 'UNet3DFPGA' or m.get('layer_order', 'cr') != 'cr':
        raise ValueError('Only UNet3DFPGA with layer_order=cr is supported')
    f0, f1 = m['f_maps']
    depth = m['depth_channels']
    widths = [(f0 // 2, m['in_channels'] * depth), (f0, f0 // 2),
              (f0, f0), (f1, f0), (f0, f0 + f1), (f0, f0),
              (m['out_channels'] * depth, f0)]
    state = checkpoint.get('model_state_dict', checkpoint)
    state = {k.removeprefix('module.'): v for k, v in state.items()}
    arrays = []
    used = set()
    for (weight_name, bias_name, key), (out_ch, in_ch) in zip(LAYERS, widths):
        kernel = 1 if key == 'final_conv' else 3
        for name, suffix, expected in [(weight_name, 'weight', (out_ch, in_ch, kernel, kernel)),
                                        (bias_name, 'bias', (out_ch,))]:
            full_key = f'{key}.{suffix}'
            tensor = state[full_key]
            if tuple(tensor.shape) != expected or tensor.dtype != torch.float32:
                raise ValueError(f'{full_key}: expected float32 {expected}, got {tensor.dtype} {tuple(tensor.shape)}')
            array = tensor.detach().cpu().numpy()
            if not np.isfinite(array).all():
                raise ValueError(f'Non-finite parameters in {full_key}')
            # Existing HLS FinalConv2D uses a redundant singleton kernel axis.
            if name == 'final_kernel':
                array = array.reshape(out_ch, in_ch, 1, 1, 1)
            arrays.append((name, full_key, array))
            used.add(full_key)
    if set(state) != used:
        raise ValueError(f'Unexported tensors: {sorted(set(state) - used)}')
    return arrays


def literal(value):
    # Nine significant decimal digits round-trip every finite float32 value.
    s = format(float(value), '.9g')
    if '.' not in s and 'e' not in s.lower():
        s += '.0'
    return s + 'f'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checkpoint', type=Path, required=True)
    parser.add_argument('--config', type=Path, required=True)
    parser.add_argument('--output-dir', type=Path, required=True)
    args = parser.parse_args()
    config = yaml.safe_load(args.config.read_text())
    checkpoint = torch.load(args.checkpoint, map_location='cpu', weights_only=True)
    arrays = extract_arrays(checkpoint, config)
    m = config['model']
    train = config['loaders']['train']
    patch = train['slice_builder']['patch_shape']
    transpose = any(t.get('whd2dhw', False) for t in train['transformer']['raw'])
    depth, height, width = (patch[2], patch[1], patch[0]) if transpose else patch
    if depth != m['depth_channels']:
        raise ValueError('Patch depth differs from model depth')
    args.output_dir.mkdir(parents=True, exist_ok=True)
    header = '''// Generated by export_unet_fpga_weights.py. Do not edit by hand.
#ifndef UNET_FPGA_WEIGHTS_H
#define UNET_FPGA_WEIGHTS_H
#ifdef UNET_FPGA_FIXED_POINT
#include <ap_fixed.h>
#ifndef UNET_FPGA_WEIGHT_TYPE
#define UNET_FPGA_WEIGHT_TYPE ap_fixed<32,16>
#endif
#endif
#ifndef UNET_FPGA_WEIGHT_TYPE
#define UNET_FPGA_WEIGHT_TYPE float
#endif
namespace unet_fpga_weights {
using weight_t = UNET_FPGA_WEIGHT_TYPE;
'''
    constants = {'INPUT_CHANNELS': m['in_channels'], 'INPUT_DEPTH': depth,
                 'INPUT_HEIGHT': height, 'INPUT_WIDTH': width,
                 'CLASS_COUNT': m['out_channels'], 'FINAL_CHANNELS': m['out_channels'] * depth,
                 'FEATURES_0': m['f_maps'][0], 'FEATURES_1': m['f_maps'][1],
                 'PARAMETER_COUNT': sum(a.size for _, _, a in arrays)}
    # k-prefixed names avoid existing HLS preprocessor macros (e.g. INPUT_DEPTH).
    header += ''.join(f'constexpr int k_{name.lower()} = {value};\n' for name, value in constants.items())
    source = ['// PyTorch OIHW kernel order; final_kernel has one extra singleton axis.\n',
              '#include "unet_weights.h"\nnamespace unet_fpga_weights {\n']
    metadata = []
    for name, key, array in arrays:
        dims = ''.join(f'[{n}]' for n in array.shape)
        header += f'// {key}\nextern weight_t {name}{dims};\n'
        source.append(f'weight_t {name}{dims} = {{\n')
        values = array.ravel(order='C')
        for start in range(0, len(values), 8):
            source.append('    ' + ', '.join(literal(x) for x in values[start:start + 8]) + ',\n')
        source.append('};\n\n')
        metadata.append({'name': name, 'checkpoint_key': key, 'shape': list(array.shape),
                         'count': int(array.size), 'min': float(array.min()), 'max': float(array.max())})
    header += '} // namespace unet_fpga_weights\n#endif\n'
    source.append('} // namespace unet_fpga_weights\n')
    (args.output_dir / 'unet_weights.h').write_text(header)
    (args.output_dir / 'unet_weights_data.cpp').write_text(''.join(source))
    manifest = {'checkpoint': str(args.checkpoint.resolve()),
                'checkpoint_sha256': hashlib.sha256(args.checkpoint.read_bytes()).hexdigest(),
                'config': str(args.config.resolve()), 'model': m,
                'best_eval_score': checkpoint.get('best_eval_score'),
                'num_iterations': checkpoint.get('num_iterations'),
                'constants': constants, 'arrays': metadata}
    (args.output_dir / 'weights_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    (args.output_dir / 'README.md').write_text('''# UNet3DFPGA weights

Generated from the checkpoint recorded in `weights_manifest.json`.
Compile `unet_weights_data.cpp` with your HLS sources and include `unet_weights.h`.
All arrays are in namespace `unet_fpga_weights`; kernels use PyTorch OIHW order,
with no spatial flipping. The final kernel has shape [classes*depth][features][1][1][1]
to match the existing HLS FinalConv2D template. It contains the same values as
PyTorch's [classes*depth][features][1][1] tensor.

Default type: float32. For HLS ap_fixed<32,16>, compile ALL translation units
with `-DUNET_FPGA_FIXED_POINT`. An alternative type can be selected using
`UNET_FPGA_WEIGHT_TYPE` (its type declaration must be visible in all units).
Fixed-point conversion quantizes parameters; arithmetic accuracy must be tested.

For this model: input NCDHW=(1,1,4,5,5), f_maps=[16,32], five output classes.
Final output channel index = class_index*4 + depth_index. Input depth is folded
into Conv2D channels. Pooled HDF5 data use WHD order: transpose (2,1,0) before input.

These files contain parameters only. The existing unet implementation needs:
- 4 input depth channels, height/width 5, feature channels 16 and 32;
- all six intermediate convolution bias arrays applied before ReLU;
- final convolution with 20 output channels and its bias;
- nearest interpolation directly from 2x2 to 5x5, matching PyTorch;
- per-voxel softmax over the five classes after reshape (for probabilities).
There are no GroupNorm parameters. Existing HLS inference code is not modified.
''')
    print(f'Exported {len(arrays)} arrays / {constants["PARAMETER_COUNT"]} parameters to {args.output_dir}')


if __name__ == '__main__':
    main()
